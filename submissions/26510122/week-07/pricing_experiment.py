"""Reproducible, small traffic split for a future opening-price comparison."""

from __future__ import annotations

import hashlib

from pricing_simulator import RATIOS, candidate_price


SEED = "week07-opening-price-v1"


def assign_price(task_id: str, item: str, reserve: int, percent: int) -> tuple[str, int | None]:
    """Return an experimental arm/ask or the unchanged legacy policy.

    A task's assignment is stable across restarts. The task ID is generated by
    A2A, not by the Seller, and the item is included in the hash input.
    """
    if type(percent) is not int or not 0 <= percent <= 100:
        raise ValueError("experiment percent must be an integer from 0 to 100")
    if percent == 0:
        return "legacy_cap_1.12", None
    digest = hashlib.sha256(f"{SEED}:{item}:{task_id}".encode("utf-8")).digest()
    if int.from_bytes(digest[:8], "big") >= percent * (1 << 64) // 100:
        return "legacy_cap_1.12", None
    arm = list(RATIOS)[int.from_bytes(digest[8:16], "big") % len(RATIOS)]
    return arm, candidate_price(reserve, arm)
