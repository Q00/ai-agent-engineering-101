"""Assemble worker/src from the week-07 sources, so the Cloudflare shop runs
the very code the market test checks on the PC.

    python build.py                 # then, from this folder:
    uv run pywrangler deploy

    copied     shop_core, buyer_core, catalog, prices, negotiation_memory,
               market_anchor (the shared shop and buyer) and entry.py (what
               only Cloudflare has)
    generated  shop_data.py: the market's three catalogue items, the
               repriced asks (asks.json), the PC's negotiation journal and the
               PC buyer's memory (.market/memory.json), which seed the Durable
               Objects the first time they start
"""
import json
import shutil
from pathlib import Path

W = Path(__file__).resolve().parent
WEEK = W.parent
SRC = W / "src"
SHARED = ["shop_core.py", "buyer_core.py", "catalog.py", "prices.py", "negotiation_memory.py",
          "market_anchor.py"]
MARKET_ITEMS = ("lamp", "chair", "bookshelf")


def main() -> int:
    SRC.mkdir(exist_ok=True)
    for name in SHARED:
        shutil.copy2(WEEK / name, SRC / name)
    shutil.copy2(W / "entry.py", SRC / "entry.py")

    items = [it for it in json.loads((WEEK / "catalog.json").read_text(encoding="utf-8"))
             if it["id"] in MARKET_ITEMS]
    asks = json.loads((WEEK / "asks.json").read_text(encoding="utf-8"))["asks"]
    episodes = []
    journal = WEEK / ".market" / "negotiations.jsonl"
    if journal.exists():
        for line in journal.read_text(encoding="utf-8").splitlines():
            try:
                episodes.append(json.loads(line))
            except ValueError:
                pass
    memory_file = WEEK / ".market" / "memory.json"
    memory = json.loads(memory_file.read_text(encoding="utf-8")) if memory_file.exists() else {}
    (SRC / "shop_data.py").write_text(
        "# Generated by worker/build.py; do not edit.\n"
        f"ITEMS = {items!r}\n\nASKS = {asks!r}\n\nEPISODES = {episodes!r}\n\nMEMORY = {memory!r}\n",
        encoding="utf-8")
    print(f"src/ built: {len(SHARED) + 1} modules, {len(items)} items {[i['id'] for i in items]}, "
          f"asks {asks}, {len(episodes)} journal episodes and {len(memory)} remembered shops to seed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
