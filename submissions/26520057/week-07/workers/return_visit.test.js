import assert from 'node:assert/strict';
import {webcrypto,generateKeyPairSync} from 'node:crypto';
import {ShopCore,returnVisit} from './shop_core.js';
import '../server/tests/mock_openai.mjs';
globalThis.crypto ||= webcrypto;
const saved = new Map();
const storage = {get:async k=>structuredClone(saved.get(k)),put:async(k,v)=>saved.set(k,structuredClone(v))};
const key = generateKeyPairSync('ed25519').privateKey.export({type:'pkcs8',format:'pem'});
const core = new ShopCore({storage}, {OPENAI_API_KEY:'test-only',SHOP_PRIVATE_KEY:key});
const send = (text,extra={})=>core.run('SendMessage',{message:{parts:[{text}],...extra}});
const first = await send('I want a lamp');
const metadata = {returnTaskId:first.id};
const started = saved.get('task:'+first.id).visitedAt;
assert.equal(await returnVisit(storage,{metadata},started+3600000),true);
assert.equal(await returnVisit(storage,{metadata},started+3600001),false);
assert.equal(await returnVisit(storage,{metadata},started-1),false);
assert.equal(await returnVisit(storage,{metadata:{returnTaskId:'../../secret'}}),false);
const offer = await send('I offer 80 for a lamp',{metadata});
assert.equal(offer.status.state,'TASK_STATE_INPUT_REQUIRED');
assert.equal(offer.metadata.premiumAS,true);
assert.match(offer.status.message.parts[0].text,/Would you accept 100 with Premium AS/);
const deal = await send('100',{taskId:offer.id});
assert.equal(deal.status.state,'TASK_STATE_COMPLETED');
assert.equal(deal.artifacts[0].parts[0].data.price,100);
assert.equal(deal.artifacts[1].name,'premium-as');
const retrieved = await core.run('GetTask',{id:deal.id});
assert.deepEqual(retrieved.artifacts,deal.artifacts);
const newcomer = await send('I offer 80 for a lamp');
assert.equal(newcomer.metadata.premiumAS,false);
const high = await send('I offer 130 for a lamp',{metadata});
assert.equal(high.artifacts[0].parts[0].data.price,100);
console.log('PASS one-hour boundary, invalid/expired code, below-floor hold, explicit acceptance, AS fulfillment/retrieval, newcomer exclusion, no price increase');
