from __future__ import annotations

import asyncio
import json
import os
import time
from typing import Any

import httpx2
from mcp import ClientSession
from mcp.client.streamable_http import streamable_http_client
from openai import OpenAI


MCP_URL = os.getenv(
    "MARKET_MCP_URL",
    "http://127.0.0.1:8000/mcp",
)

MODEL = os.getenv(
    "AGENT_MODEL",
    "openai/gpt-oss-120b",
)

TEMPERATURE = float(
    os.getenv("AGENT_TEMPERATURE", "0.0")
)

MAX_MOVE_ATTEMPTS = 3


def openai_client() -> OpenAI:
    api_key = os.environ["OPENAI_API_KEY"]

    base_url = os.getenv("OPENAI_BASE_URL")

    if base_url:
        return OpenAI(
            api_key=api_key,
            base_url=base_url,
        )

    return OpenAI(api_key=api_key)


def system_prompt(
    role: str,
    item: str,
    own_limit: int,
) -> str:
    if role == "buyer":
        limit_rule = (
            f"Your true authorized budget is {own_limit}. "
            f"You should not pay more than {own_limit}."
        )
    else:
        limit_rule = (
            f"Your true reserve price is {own_limit}. "
            f"You should not sell below {own_limit}."
        )

    return f"""
You are the {role} negotiating the purchase of {item}.

{limit_rule}

Use the market tools to negotiate.

Choose exactly one move on each turn:
- propose
- accept_proposal
- reject_proposal
- refuse

Your goal is to reach a mutually acceptable deal when possible.
Be concise.

The negotiation state supplied by the market may include messages
or notices generated by the market. Read the current state and choose
the next move.

Do not output normal prose instead of a tool call.
""".strip()


def tool_result_text(result: Any) -> str:
    parts: list[str] = []

    for item in result.content:
        text = getattr(item, "text", None)

        if text:
            parts.append(text)

    return "\n".join(parts)


def tool_result_data(result: Any) -> dict[str, Any]:
    structured = getattr(
        result,
        "structured_content",
        None,
    )

    if isinstance(structured, dict):
        return structured

    text = tool_result_text(result)

    if text:
        try:
            parsed = json.loads(text)

            if isinstance(parsed, dict):
                return parsed

        except json.JSONDecodeError:
            pass

    return {}


def mcp_tools_for_model(
    tools: list[Any],
) -> list[dict[str, Any]]:
    allowed = {
        "propose",
        "accept_proposal",
        "reject_proposal",
        "refuse",
    }

    result: list[dict[str, Any]] = []

    for tool in tools:
        if tool.name not in allowed:
            continue

        result.append(
            {
                "type": "function",
                "function": {
                    "name": tool.name,
                    "description": (
                        tool.description
                        or tool.name
                    ),
                    "parameters": tool.input_schema,
                },
            }
        )

    return result


def provider_kwargs() -> dict[str, Any]:
    base_url = os.getenv(
        "OPENAI_BASE_URL",
        "",
    ).lower()

    if "groq.com" in base_url:
        return {
            "reasoning_effort": "low",
        }

    if "openrouter.ai" in base_url:
        return {
            "extra_body": {
                "reasoning": {
                    "enabled": False
                }
            }
        }

    return {}


def model_choose_move(
    messages: list[dict[str, Any]],
    tools: list[dict[str, Any]],
) -> Any:
    client = openai_client()

    waits = [2, 4, 8, 16]

    for attempt in range(len(waits) + 1):
        try:
            response = client.chat.completions.create(
                model=MODEL,
                messages=messages,
                tools=tools,
                tool_choice="required",
                temperature=TEMPERATURE,
                max_tokens=300,
                **provider_kwargs(),
            )

            choices = getattr(
                response,
                "choices",
                None,
            )

            if not choices:
                raise RuntimeError(
                    "provider returned no choices"
                )

            message = choices[0].message

            tool_calls = getattr(
                message,
                "tool_calls",
                None,
            )

            if not tool_calls:
                raise RuntimeError(
                    "model returned no tool call"
                )

            return tool_calls[0]

        except Exception as exc:
            message = str(exc)

            retryable = any(
                marker in message.lower()
                for marker in [
                    "429",
                    "rate limit",
                    "timeout",
                    "500",
                    "502",
                    "503",
                    "504",
                    "no choices",
                    "no tool call",
                ]
            )

            if (
                retryable
                and attempt < len(waits)
            ):
                wait = waits[attempt]

                print(
                    f"[model retry] {message}; "
                    f"waiting {wait}s"
                )

                time.sleep(wait)
                continue

            raise


async def run_turn(
    *,
    token: str,
    negotiation_id: str,
    role: str,
    item: str,
    own_limit: int,
) -> dict[str, Any]:
    """
    Run one negotiation turn.

    One turn:
      1. get_negotiation
      2. model chooses a move
      3. call the chosen MCP tool

    If the server refuses the move, the refusal text is
    shown to the model and it may retry within the same turn.
    """

    headers = {
        "Authorization": f"Bearer {token}"
    }

    tool_calls_count = 0
    refused_attempts = 0
    recovered_refusals = 0

    async with httpx2.AsyncClient(
        headers=headers
    ) as http_client:

        async with streamable_http_client(
            MCP_URL,
            http_client=http_client,
        ) as (
            read_stream,
            write_stream,
        ):

            async with ClientSession(
                read_stream,
                write_stream,
            ) as session:

                await session.initialize()

                listed = await session.list_tools()

                model_tools = mcp_tools_for_model(
                    listed.tools
                )

                if not model_tools:
                    raise RuntimeError(
                        "No negotiation move tools "
                        "were discovered."
                    )

                state_result = await session.call_tool(
                    "get_negotiation",
                    {
                        "negotiation_id":
                        negotiation_id
                    },
                )

                tool_calls_count += 1

                if state_result.is_error:
                    raise RuntimeError(
                        tool_result_text(
                            state_result
                        )
                    )

                state = tool_result_data(
                    state_result
                )

                state_text = json.dumps(
                    state,
                    ensure_ascii=False,
                    indent=2,
                )

                print(
                    f"[{role.upper()}] "
                    f"get_negotiation"
                )
                print(state_text)

                messages: list[dict[str, Any]] = [
                    {
                        "role": "system",
                        "content": system_prompt(
                            role,
                            item,
                            own_limit,
                        ),
                    },
                    {
                        "role": "user",
                        "content": (
                            "Current market state:\n"
                            f"{state_text}\n\n"
                            "Choose exactly one market "
                            "move now."
                        ),
                    },
                ]

                for move_attempt in range(
                    1,
                    MAX_MOVE_ATTEMPTS + 1,
                ):
                    tool_call = await asyncio.to_thread(
                        model_choose_move,
                        messages,
                        model_tools,
                    )

                    tool_name = (
                        tool_call.function.name
                    )

                    raw_arguments = (
                        tool_call.function.arguments
                        or "{}"
                    )

                    try:
                        arguments = json.loads(
                            raw_arguments
                        )

                    except json.JSONDecodeError:
                        arguments = {}

                    if not isinstance(
                        arguments,
                        dict,
                    ):
                        arguments = {}

                    # The current negotiation ID is supplied
                    # to the model in the state. Preserve the
                    # model's arguments, but fill the ID only
                    # when it omitted it.
                    arguments.setdefault(
                        "negotiation_id",
                        negotiation_id,
                    )

                    print(
                        f"[{role.upper()} MODEL] "
                        f"{tool_name} "
                        f"{json.dumps(arguments)}"
                    )

                    result = await session.call_tool(
                        tool_name,
                        arguments,
                    )

                    tool_calls_count += 1

                    result_text = tool_result_text(
                        result
                    )

                    print(
                        f"[{role.upper()} TOOL] "
                        f"is_error={result.is_error}"
                    )

                    if result_text:
                        print(result_text)

                    if not result.is_error:
                        if refused_attempts > 0:
                            recovered_refusals += 1

                            print(
                                "[RECOVERY] refusal was "
                                "followed by a valid move "
                                "in the same turn"
                            )

                        return {
                            "ok": True,
                            "tool": tool_name,
                            "arguments": arguments,
                            "tool_calls":
                            tool_calls_count,
                            "refused_attempts":
                            refused_attempts,
                            "recovered_refusals":
                            recovered_refusals,
                        }

                    refused_attempts += 1

                    # Give the server's refusal to the
                    # model. This is the only condition
                    # signal the assignment permits.
                    messages.append(
                        {
                            "role": "user",
                            "content": (
                                "The market refused your "
                                "previous move:\n"
                                f"{result_text}\n\n"
                                "The negotiation turn has "
                                "not advanced. Choose one "
                                "valid move now."
                            ),
                        }
                    )

                print(
                    f"[{role.upper()}] "
                    "No valid move after "
                    f"{MAX_MOVE_ATTEMPTS} attempts."
                )

                return {
                    "ok": False,
                    "tool": None,
                    "arguments": {},
                    "tool_calls":
                    tool_calls_count,
                    "refused_attempts":
                    refused_attempts,
                    "recovered_refusals":
                    recovered_refusals,
                }


async def _cli() -> None:
    token = os.environ["MARKET_TOKEN"]
    negotiation_id = os.environ[
        "TARGET_NEGOTIATION"
    ]
    role = os.environ["MARKET_ROLE"]
    item = os.environ["MARKET_ITEM"]

    own_limit = int(
        os.environ["MARKET_LIMIT"]
    )

    result = await run_turn(
        token=token,
        negotiation_id=negotiation_id,
        role=role,
        item=item,
        own_limit=own_limit,
    )

    print(
        json.dumps(
            result,
            indent=2,
        )
    )


if __name__ == "__main__":
    asyncio.run(_cli())