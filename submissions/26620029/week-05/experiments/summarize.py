"""Aggregate experiments/<EXP>/results.csv into experiments/SUMMARY.md.

    python experiments/summarize.py                 # reads experiments/*/results.csv
    python experiments/summarize.py --out-root experiments/_mock
"""
from __future__ import annotations

import argparse
import csv
import math
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ORDER = ["prompt", "server", "prompt_inject", "server_inject"]


def note_num(note: str, key: str) -> float:
    m = re.search(rf"\b{key}=([-\d.na]+)", note)
    try:
        return float(m.group(1)) if m else math.nan
    except ValueError:
        return math.nan


def mean(xs):
    xs = [x for x in xs if not math.isnan(x)]
    return sum(xs) / len(xs) if xs else math.nan


def fmt(x, d=2):
    return "-" if isinstance(x, float) and math.isnan(x) else f"{x:.{d}f}"


def summarize(path: Path) -> list[str]:
    with path.open(encoding="utf-8", newline="") as f:
        rows = [r for r in csv.DictReader(f) if r["outcome"]]
    crashed = 0
    with path.open(encoding="utf-8", newline="") as f:
        crashed = sum(1 for r in csv.DictReader(f) if not r["outcome"])
    out = [f"## {path.parent.name}", ""]
    if rows:
        out.append(f"{rows[0]['note'].split(' seed=')[0]}  (crashed episodes: {crashed})")
        out.append("")
    out += ["| condition | n | correct | deal | open | no_deal | violation | attempted | refused (limit/turn) "
            "| recovered same turn | self-accepts | mean turns | LLM calls/ep | buyer P(over limit) with notice | without notice |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    conds = sorted({r["condition"] for r in rows}, key=lambda c: ORDER.index(c) if c in ORDER else 9)
    for c in conds:
        rs = [r for r in rows if r["condition"] == c]
        n = len(rs)
        cnt = lambda key, val: sum(1 for r in rs if r[key] == val)  # noqa: E731
        s = lambda key: sum(int(r[key] or 0) for r in rs)            # noqa: E731
        nsum = lambda key: sum(note_num(r["note"], key) for r in rs)  # noqa: E731
        out.append(
            f"| {c} | {n} | {s('correct')}/{n} | {cnt('outcome', 'deal')} | {cnt('outcome', 'open')} | "
            f"{cnt('outcome', 'no_deal')} | {s('violation')} | {s('attempted_violations')} | "
            f"{s('refused_calls')} ({int(nsum('refused_limit'))}/{int(nsum('refused_turn'))}) | "
            f"{int(nsum('recovered_same_turn'))} | {int(nsum('self_accepts'))} | {fmt(mean([float(r['turns']) for r in rs]))} | "
            f"{fmt(mean([note_num(r['note'], 'llm_calls') for r in rs]), 1)} | "
            f"{fmt(mean([note_num(r['note'], 'buyer_p_over_with_notice') for r in rs]), 3)} | "
            f"{fmt(mean([note_num(r['note'], 'buyer_p_over_without_notice') for r in rs]), 3)} |")
    out.append("")
    # per scenario: where do deals / violations happen
    out += ["| condition | scenario | deal_possible | outcomes | prices | violations |", "|---|---|---|---|---|---|"]
    for c in conds:
        for sid in sorted({r["scenario"] for r in rows if r["condition"] == c}, key=int):
            rs = [r for r in rows if r["condition"] == c and r["scenario"] == sid]
            outc = ", ".join(f"{o}={sum(1 for r in rs if r['outcome'] == o)}" for o in ("deal", "open", "no_deal")
                             if any(r["outcome"] == o for r in rs))
            prices = ",".join(r["price"] for r in rs if r["price"]) or "-"
            out.append(f"| {c} | {sid} | {rs[0]['deal_possible']} | {outc} | {prices} | "
                       f"{sum(int(r['violation'] or 0) for r in rs)} |")
    out.append("")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-root", type=Path, default=HERE)
    args = ap.parse_args()
    files = sorted(args.out_root.glob("*/results.csv"))
    lines = ["# Week-05 additional experiments (Jev host) - summary", "",
             "Generated by summarize.py from experiments/<EXP>/results.csv. "
             "'buyer P(over limit)' is the mean probability Jev put on buyer actions that would break "
             "the real budget, split by whether a market_notice was in the observation.", ""]
    for p in files:
        lines += summarize(p)
    target = args.out_root / "SUMMARY.md"
    target.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"\nwrote {target}")


if __name__ == "__main__":
    main()
